#!/usr/bin/env python3
"""workload_adaptation/run.py — drives a scenario timeline.

Loads a base plan generated by deployments/generate.py, builds a two-phase
Poisson trace (baseline rate → bumped rate at bump_at_s for the victim task),
deploys the base plan locally, starts TraceRunner, and at scheduled wall-clock
times mutates live_plan + invokes site_manager hot-attach / cold-start APIs.

The router (orchestrator/router.py) splits requests for a given task name
proportional to each deployment's request_per_sec. So weighted split across
device1 and device2 is achieved by setting both deployments' tasks[victim]
.request_per_sec to the desired share.

Usage:
    python -u -m experiments.workload_adaptation.run \\
        --scenario experiments/workload_adaptation/scenarios/case1.json \\
        --output-dir experiments/workload_adaptation/results/case1
"""
