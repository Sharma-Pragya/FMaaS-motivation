# ────────────────────────────────────────────────────────────────────
# Trace construction (two-phase)
# ────────────────────────────────────────────────────────────────────

def _build_two_phase_trace(cfg, plan: dict, seed: int):
    """Generate a Poisson trace with a step change in the victim task's rate.

    Non-victim tasks: constant rate = per_app_rps for the full duration.
    Victim task: baseline_rps for [0, bump_at), then bumped_rps for [bump_at, stop).

    Returns a flat sorted list of Request objects.
    """
    adapt = cfg.adaptation
    victim = adapt["victim_task"]
    bump_at = float(adapt["bump_at_s"])
    stop_at = float(adapt["stop_at_s"])
    baseline = float(adapt["baseline_rps"])
    bumped = float(adapt["bumped_rps"])

    # All distinct task names in the base plan (including victim).
    task_names = []
    for site in plan["sites"]:
        for dep in site["deployments"]:
            for t in dep.get("tasks", {}):
                if t not in task_names:
                    task_names.append(t)

    # Per-task seed: prefer cfg.tasks[t]['seed'] if present.
    tasks_dict = {t: {"seed": cfg.tasks[t]["seed"]} for t in task_names if t in cfg.tasks}

    # ── Phase A: [0, bump_at) — everyone at baseline / per_app_rps ──
    rate_a = {t: float(cfg.per_app_rps) for t in task_names}
    if victim in rate_a:
        rate_a[victim] = baseline

    # generate_requests expects req_rate as a list ordered by sorted(task_names).
    sorted_a = sorted(rate_a.keys())
    rate_list_a = [rate_a[t] for t in sorted_a]
    reqs_a, _, _ = poisson_requests(
        rate_list_a, bump_at, sorted_a, seed=seed, req_id_offset=0,
        tasks_dict={t: tasks_dict[t] for t in sorted_a if t in tasks_dict},
    )

    # ── Phase B: [bump_at, stop_at) — victim at bumped_rps, rest unchanged ──
    rate_b = dict(rate_a)
    if victim in rate_b:
        rate_b[victim] = bumped
    sorted_b = sorted(rate_b.keys())
    rate_list_b = [rate_b[t] for t in sorted_b]

    # Use a different seed for phase B so the streams aren't identical, but
    # keep it deterministic relative to the base seed.
    reqs_b, _, _ = poisson_requests(
        rate_list_b, stop_at - bump_at, sorted_b,
        seed=seed + 1, req_id_offset=10**6,
        tasks_dict={t: {"seed": tasks_dict[t]["seed"] + 1} for t in sorted_b if t in tasks_dict},
    )
    # Shift phase B times into absolute timeline.
    for r in reqs_b:
        r.req_time = r.req_time + bump_at

    combined = list(reqs_a) + list(reqs_b)
    combined.sort(key=lambda r: r.req_time)
    return combined


# ────────────────────────────────────────────────────────────────────
# Plan helpers (operating on live_plan in-place)
# ────────────────────────────────────────────────────────────────────

def _find_deployment(plan: dict, device_name: str, backbone: str) -> dict:
    for site in plan["sites"]:
        for dep in site["deployments"]:
            if dep["device_name"] == device_name and dep["backbone"] == backbone:
                return dep
    raise KeyError(f"no deployment for device={device_name} backbone={backbone}")


def _set_task_rps(plan: dict, device_name: str, backbone: str,
                  task: str, rps: float) -> None:
    dep = _find_deployment(plan, device_name, backbone)
    block = dep.setdefault("tasks", {})
    entry = block.setdefault(task, {"type": "forecasting"})
    entry["request_per_sec"] = float(rps)
    entry["total_requested_workload"] = float(rps)


def _add_mirror_decoder_to_plan(plan: dict, device_name: str, backbone: str,
                                task: str, base_task: str,
                                decoder_type: str, decoder_path: str,
                                rps: float) -> dict:
    dep = _find_deployment(plan, device_name, backbone)
    decoders = dep.setdefault("decoders", [])
    # Avoid duplicate decoder entries.
    if not any(d.get("task") == task for d in decoders):
        decoders.append({
            "task": task,
            "base_task": base_task,
            "type": decoder_type,
            "path": decoder_path,
        })
    _set_task_rps(plan, device_name, backbone, task, rps)
    return dep


def _build_cold_start_spec(cfg, plan: dict) -> dict:
    """Build a deployment spec for case 2's runtime backbone spin-up."""
    adapt = cfg.adaptation
    dev_name = adapt["offload_target_device"]
    dev_meta = cfg.devices[dev_name]
    port = int(adapt["offload_target_port"])
    backbone = adapt["offload_target_backbone"]

    # Pull experiment defaults consistent with what generate.py emits.
    exp = cfg.experiment
    spec = {
        "device": f"{dev_meta['ip']}:{port}",
        "device_name": dev_name,
        "device_type": dev_meta["type"],
        "backbone": backbone,
        "cuda": dev_meta["cuda"],
        "scheduler_policy": "stfq",
        "worker_mode": "threaded",
        "decoders": [],            # decoder attached AFTER load via add_decoder
        "tasks": {},               # filled in when we attach the decoder
        "max_batch_size": exp.get("max_batch_size", 32),
        "max_batch_wait_ms": exp.get("max_batch_wait_ms", 0),
        "isolation_mode": exp.get("isolation_mode", "shared"),
        "max_model_len": exp.get("max_model_len", 256),
        "gpu_memory_utilization": 0.42,   # leave room for the dinosmall on :8000
    }
    if "offload_target_tpc_partition" in adapt:
        spec["tpc_mode"] = "libsmctrl"
        spec["tpc_partition"] = list(adapt["offload_target_tpc_partition"])
    return spec


# ────────────────────────────────────────────────────────────────────
# Timeline executor
# ────────────────────────────────────────────────────────────────────

class ScenarioRunner:
    def __init__(self, scenario_path: Path, output_dir: Path, seed: int = 42):
        self.scenario = json.loads(scenario_path.read_text())
        self.output_dir = output_dir
        self.seed = seed

        cfg_module = self.scenario["config_module"]
        self.cfg = importlib.import_module(cfg_module)

        # Resolve base_plan path relative to scenario dir.
        base_plan_path = (SCENARIO_DIR / self.scenario["base_plan"]).resolve()
        if not base_plan_path.is_file():
            raise FileNotFoundError(
                f"base plan not found: {base_plan_path} — run "
                f"deployments/generate.py --case {self.scenario['case']} first."
            )
        self.base_plan = json.loads(base_plan_path.read_text())

        self.events: list = []   # (t_seconds, label, dict) for the metric overlay

    def _record_event(self, label: str, params: dict | None = None):
        ts = time.time()
        self.events.append({"epoch": ts, "label": label, "params": params or {}})
        print(f"[scenario] t={ts:.3f} event={label} params={params}")

    def _apply_runtime_defaults(self, plan: dict) -> None:
        """Mirror cluster_sharing_benefit/run.py._apply_runtime_defaults."""
        from collections import Counter
        exp = self.cfg.experiment
        counts = Counter()
        for site in plan.get("sites", []):
            for dep in site.get("deployments", []):
                host = dep["device"].rsplit(":", 1)[0]
                counts[(host, dep.get("cuda", ""))] += 1
        for site in plan.get("sites", []):
            for dep in site.get("deployments", []):
                dep.setdefault("max_batch_size", exp.get("max_batch_size", 32))
                dep.setdefault("max_batch_wait_ms", exp.get("max_batch_wait_ms", 0))
                dep.setdefault("isolation_mode", exp.get("isolation_mode", "shared"))
                if exp.get("max_model_len") is not None:
                    dep.setdefault("max_model_len", exp["max_model_len"])
                host = dep["device"].rsplit(":", 1)[0]
                n = counts.get((host, dep.get("cuda", "")), 1)
                dep.setdefault("gpu_memory_utilization", round(0.85 / n, 4))
                tasks_block = dep.get("tasks", {})
                for t in list(tasks_block.keys()):
                    rate = float(tasks_block[t].get("request_per_sec", 0.0))
                    tasks_block[t]["request_per_sec"] = rate
                    tasks_block[t]["total_requested_workload"] = rate

    async def _wait_until(self, start_epoch: float, t_seconds: float):
        target = start_epoch + t_seconds
        delay = target - time.time()
        if delay > 0:
            await asyncio.sleep(delay)

    async def _timeline_case1(self, runner: TraceRunner, start_epoch: float):
        adapt = self.cfg.adaptation
        victim = adapt["victim_task"]
        bumped = float(adapt["bumped_rps"])
        share_dev2 = float(adapt["mirror_share_post_attach"])

        # Step 1: bump_at — mutate live_plan to advertise the bumped rate on
        # device1 (router still routes 100% there until attach). The trace
        # itself fires the bumped traffic — this just keeps the live_plan
        # consistent with what the trace is doing.
        await self._wait_until(start_epoch, adapt["bump_at_s"])
        self._record_event("bump_rps", {"task": victim, "new_rps": bumped})
        _set_task_rps(runner.live_plan,
                      adapt["victim_origin_device"], "momentlarge",
                      victim, bumped)
        runner.invalidate_plan_cache()

        # Step 2: attach_at — hot-attach decoder on device2's already-running
        # momentlarge backbone, then update routing weights in live_plan.
        await self._wait_until(start_epoch, adapt["attach_at_s"])
        self._record_event("attach_decoder", {
            "device": adapt["offload_target_device"],
            "task": victim,
        })
        # Find device2's momentlarge gRPC URL from the base plan.
        target_dep = _find_deployment(
            runner.live_plan,
            adapt["offload_target_device"],
            adapt["offload_target_backbone"],
        )
        decoder_spec = [{
            "task": victim,
            "base_task": adapt["victim_base_task"],
            "type": adapt["victim_decoder_type"],
            "path": adapt["victim_decoder_path"],
        }]
        attach_t0 = time.time()
        result = await _add_decoder_to_device(target_dep["device"], decoder_spec)
        attach_e2e_ms = (time.time() - attach_t0) * 1000.0
        device_summary = result.get("logger_summary") if isinstance(result, dict) else None
        print(f"[scenario] add_decoder e2e={attach_e2e_ms:.1f} ms "
              f"device_summary={device_summary}")
        self._record_event("attach_decoder_done", {
            "device": adapt["offload_target_device"],
            "task": victim,
            "attach_e2e_ms": attach_e2e_ms,
            "device_logger_summary": device_summary,
            "result_status": (result or {}).get("status") if isinstance(result, dict) else None,
        })

        # Update live_plan: split RPS between device1 and device2.
        rps_dev1 = bumped * (1.0 - share_dev2)
        rps_dev2 = bumped * share_dev2
        _set_task_rps(runner.live_plan,
                      adapt["victim_origin_device"], "momentlarge",
                      victim, rps_dev1)
        # Add task entry + decoder bookkeeping to device2's deployment.
        _add_mirror_decoder_to_plan(
            runner.live_plan,
            adapt["offload_target_device"],
            adapt["offload_target_backbone"],
            task=victim,
            base_task=adapt["victim_base_task"],
            decoder_type=adapt["victim_decoder_type"],
            decoder_path=adapt["victim_decoder_path"],
            rps=rps_dev2,
        )
        runner.invalidate_plan_cache()
        self._record_event("split_traffic", {
            "task": victim,
            "device1_rps": rps_dev1,
            "device2_rps": rps_dev2,
        })

    async def _timeline_case2(self, runner: TraceRunner, start_epoch: float):
        adapt = self.cfg.adaptation
        victim = adapt["victim_task"]
        bumped = float(adapt["bumped_rps"])
        share_dev2 = float(adapt["mirror_share_post_attach"])

        # Step 1: bump_at — mutate live_plan, trace fires the spike.
        await self._wait_until(start_epoch, adapt["bump_at_s"])
        self._record_event("bump_rps", {"task": victim, "new_rps": bumped})
        _set_task_rps(runner.live_plan,
                      adapt["victim_origin_device"], "momentlarge",
                      victim, bumped)
        runner.invalidate_plan_cache()

        # Step 2: spinup_at — start a fresh momentlarge backbone on device2:8010.
        # This blocks ~30s+ for SSH + model load. During this time device1 is
        # absorbing the full bumped load by itself — that's the spike.
        await self._wait_until(start_epoch, adapt["spinup_at_s"])
        self._record_event("start_backbone_begin", {
            "device": adapt["offload_target_device"],
            "backbone": adapt["offload_target_backbone"],
            "port": adapt["offload_target_port"],
        })
        spec = _build_cold_start_spec(self.cfg, runner.live_plan)
        deploy_status = await _deploy_one(spec)
        print(f"[scenario] _deploy_one result: {deploy_status}")
        # Add the new deployment skeleton to live_plan so subsequent steps and
        # routing updates can find it.
        runner.live_plan["sites"][0]["deployments"].append({
            **spec,
            "tasks": {},
            "decoders": [],
        })
        runner.invalidate_plan_cache()
        self._record_event("start_backbone_done", {
            "device": adapt["offload_target_device"],
        })

        # Step 3: attach_at — attach the mirror decoder and update routing.
        await self._wait_until(start_epoch, adapt["attach_at_s"])
        self._record_event("attach_decoder", {
            "device": adapt["offload_target_device"],
            "task": victim,
        })
        target_dep = _find_deployment(
            runner.live_plan,
            adapt["offload_target_device"],
            adapt["offload_target_backbone"],
        )
        decoder_spec = [{
            "task": victim,
            "base_task": adapt["victim_base_task"],
            "type": adapt["victim_decoder_type"],
            "path": adapt["victim_decoder_path"],
        }]
        result = await _add_decoder_to_device(target_dep["device"], decoder_spec)
        print(f"[scenario] add_decoder result: {result}")

        rps_dev1 = bumped * (1.0 - share_dev2)
        rps_dev2 = bumped * share_dev2
        _set_task_rps(runner.live_plan,
                      adapt["victim_origin_device"], "momentlarge",
                      victim, rps_dev1)
        _add_mirror_decoder_to_plan(
            runner.live_plan,
            adapt["offload_target_device"],
            adapt["offload_target_backbone"],
            task=victim,
            base_task=adapt["victim_base_task"],
            decoder_type=adapt["victim_decoder_type"],
            decoder_path=adapt["victim_decoder_path"],
            rps=rps_dev2,
        )
        runner.invalidate_plan_cache()
        self._record_event("split_traffic", {
            "task": victim,
            "device1_rps": rps_dev1,
            "device2_rps": rps_dev2,
        })

    def prepare(self):
        """Synchronous setup: write artifacts, build trace, deploy base plan."""
        os.makedirs(self.output_dir, exist_ok=True)
        adapt = self.cfg.adaptation

        plan = json.loads(json.dumps(self.base_plan))
        self._apply_runtime_defaults(plan)

        with open(self.output_dir / "deployment_plan.json", "w") as f:
            json.dump(plan, f, indent=2)
        with open(self.output_dir / "scenario_resolved.json", "w") as f:
            json.dump({
                "scenario": self.scenario,
                "adaptation": adapt,
                "experiment": self.cfg.experiment,
                "seed": self.seed,
            }, f, indent=2, default=str)

        trace = _build_two_phase_trace(self.cfg, plan, self.seed)
        print(f"[scenario] generated {len(trace)} requests over "
              f"[0, {adapt['stop_at_s']}s)")

        site_mgr = LocalSiteManager(str(self.output_dir))
        site_mgr.deploy(plan, str(self.output_dir))

        runner = TraceRunner(
            site_mgr.live_plan, trace, str(self.output_dir),
            pretrace_warmup_secs=float(self.cfg.experiment.get("pretrace_warmup_secs", 0.0)),
        )
        return site_mgr, runner

    async def run_async(self, runner: TraceRunner) -> None:
        await runner.warmup()
        warmup_gap = float(self.cfg.experiment.get("warmup_gap", 2.0))
        start_epoch = time.time() + warmup_gap
        print(f"[scenario] warmup done. Trace starts in {warmup_gap}s "
              f"(epoch={start_epoch:.3f})")
        await asyncio.sleep(warmup_gap)

        self._record_event("trace_start", {"start_epoch": start_epoch})

        # Scenario picks the timeline by `mode` field. Falls back to mapping
        # case names to modes for back-compat.
        mode = self.scenario.get("mode")
        if mode is None:
            mode = ("hot_attach" if self.scenario["case"] in ("case1", "case3")
                    else "cold_start_then_attach")
        timeline_fn = (self._timeline_case1
                       if mode == "hot_attach"
                       else self._timeline_case2)
        run_task = asyncio.create_task(runner.run(start_epoch=start_epoch))
        timeline_task = asyncio.create_task(timeline_fn(runner, start_epoch))

        done, _ = await asyncio.wait(
            {run_task, timeline_task}, return_when=asyncio.ALL_COMPLETED,
        )
        for t in done:
            exc = t.exception()
            if exc is not None:
                raise exc

        self._record_event("trace_end", {})

    def finalize(self, runner: TraceRunner | None):
        if runner is not None:
            runner.save_results()
        with open(self.output_dir / "scenario_events.json", "w") as f:
            json.dump(self.events, f, indent=2)
        print(f"[scenario] events written to {self.output_dir}/scenario_events.json")


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--scenario", required=True)
    ap.add_argument("--output-dir", required=True)
    ap.add_argument("--seed", type=int, default=42)
    args = ap.parse_args()

    out = Path(os.path.abspath(args.output_dir))
    sc_path = Path(args.scenario)
    if not sc_path.is_absolute():
        sc_path = (Path.cwd() / sc_path).resolve()
    scenario = ScenarioRunner(sc_path, out, seed=args.seed)

    site_mgr, runner = scenario.prepare()
    try:
        asyncio.run(scenario.run_async(runner))
    finally:
        scenario.finalize(runner)
        site_mgr.cleanup()
    print(f"[scenario] done. Results in {out}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
